import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ stdin: { contents: `export * as THREE from 'three';
export { Exam06ApproachLane } from './src/game/exercises/Exam06ApproachLane';
export { ExamEngine } from './src/game/ExamEngine';`, resolveDir: process.cwd() },
bundle: true, write: false, platform: 'node', format: 'cjs' });
const module = { exports: {} };
new Function('module', 'exports', bundle.outputFiles[0].text)(module, module.exports);
const { THREE, Exam06ApproachLane, ExamEngine } = module.exports;
const road = new THREE.Group();
road.position.set(34, 0, -42); road.rotation.y = -Math.PI / 2;
const rule = { road, widthM: 7.4, lengthM: 26 };
const checker = new Exam06ApproachLane();
const pos = (x, z) => new THREE.Vector3(x, 0, z);
const tick = (x, z) => checker.update(road, 7.4, 26, pos(x,z), pos(x-2.1,z));
assert.equal(tick(40,-40.15), false, 'lane 1 is valid');
assert.equal(tick(40,-42.89), false, 'body has not reached lane 2 centre');
assert.equal(tick(40,-42.91), true, 'body touches lane 2 centre');
checker.reset();
assert.equal(tick(40,-43.85), true, 'lane 2 centre is invalid');
checker.reset(); tick(40,-40.15); tick(18,-40.15);
assert.equal(tick(40,-43.85), false, 'later return is excluded');
checker.reset();
assert.equal(tick(60,-43.85), false, 'outside road is excluded');
const engine = new ExamEngine('normal');
engine.wireTrafficLights({ trafficLights: [], getTrafficLight: () => undefined, exam05To06LaneRule: rule });
engine.activeIndex = 5; engine.scoringStarted = true;
const snapshot = { position: pos(40,-43.85), frontPosition: pos(37.9,-43.85),
 speedKmh: 10, rpm: 800, engineRunning: true, stalled: false, leftSignal: false, seatBeltFastened: true };
engine.update(snapshot, 'green', .016);
assert.equal(engine.disqualified, true);
assert.equal(engine.disqualifyReason, 'đi không đúng làn đường quy định');
engine.reset();
assert.equal(engine.disqualified, false);
const south = new THREE.Group();
south.position.set(21,0,-78.05);
const southCheck = new Exam06ApproachLane();
const southTick = (x,z) => southCheck.update(south,8,68,pos(x,z),pos(x,z-2.1));
assert.equal(southTick(23,-70),false,'southRoad lane 1 is valid');
assert.equal(southTick(20,-70),false,'not yet touching lane 2 centre');
assert.equal(southTick(19.94,-70),true,'body touches lane 2 centre at x=19');
southCheck.reset();
assert.equal(southTick(19,-70),true,'southRoad lane 2 is invalid');
southCheck.reset(); southTick(23,-70); southTick(28,-95);
assert.equal(southTick(19,-70),false,'later southRoad return is excluded');
const southEngine = new ExamEngine('normal');
southEngine.wireTrafficLights({trafficLights:[],getTrafficLight:()=>undefined,
 exam05To06LaneRule:{road:south,widthM:8,lengthM:68}});
southEngine.activeIndex=4; southEngine.scoringStarted=true;
southEngine.update({...snapshot,position:pos(19,-70),frontPosition:pos(19,-72.1)},'green',.016);
assert.equal(southEngine.disqualified,true);
assert.equal(southEngine.disqualifyReason,'đi không đúng làn đường quy định');
console.log('Exam 5 to 6 lane checks passed, including southRoad');
